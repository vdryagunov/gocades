#!/bin/sh
# Generates error_names.go from the CryptoPro error headers.
#
#   ./scripts/gen-error-names.sh > error_names.go
#   ./scripts/gen-error-names.sh /path/to/CSP_WinError.h /path/to/include/pki
#
# CSP_WinError.h lives next to the CSP headers, the TSP/OCSP/CAdES client
# headers (tspcli_e.h, ocspcli_e.h, cades_e.h) next to cades.h. Both the Linux
# (/opt/cprocsp/include) and the macOS (app bundle) SDK layouts are searched.
# Run it after a CryptoPro update to pick up newly defined HRESULT codes.
set -eu

HEADER=${1:-CSP_WinError.h}
PKI_DIR=${2:-}

if [ ! -f "$HEADER" ]; then
	for candidate in \
		/opt/cprocsp/include/cpcsp/CSP_WinError.h \
		/Applications/CryptoPro_ECP.app/Contents/Resources/include/cpcsp/CSP_WinError.h
	do
		if [ -f "$candidate" ]; then
			HEADER=$candidate
			break
		fi
	done
fi

if [ ! -f "$HEADER" ]; then
	echo "CSP_WinError.h not found; pass its path as the first argument" >&2
	exit 1
fi

if [ -z "$PKI_DIR" ]; then
	for candidate in \
		/Applications/CryptoPro_ECP.app/Contents/Resources/include/pki \
		/opt/cprocsp/include/pki
	do
		if [ -f "$candidate/tspcli_e.h" ]; then
			PKI_DIR=$candidate
			break
		fi
	done
fi

PKI_HEADERS=
for name in tspcli_e.h ocspcli_e.h cades_e.h; do
	if [ -n "$PKI_DIR" ] && [ -f "$PKI_DIR/$name" ]; then
		PKI_HEADERS="$PKI_HEADERS $PKI_DIR/$name"
	else
		echo "warning: $name not found, its codes are skipped" >&2
	fi
done

echo "// Code generated by scripts/gen-error-names.sh; DO NOT EDIT."
echo "//"
for src in "$HEADER" $PKI_HEADERS; do
	echo "// Source: $src"
done
echo
echo "package gocades"
echo
echo "// errorNames maps CryptoAPI/CryptoPro HRESULT values to their symbolic"
echo "// names, for diagnostics. Unknown codes simply fall through to hex."
echo "var errorNames = map[uint32]string{"
# shellcheck disable=SC2086
awk '
function pad(s, n) {
	while (length(s) < n) {
		s = "0" s
	}
	return s
}
function add(hex, name) {
	# Only failure codes matter for error reporting.
	if (length(hex) != 8 || hex < "80000000") {
		return
	}
	if (!(hex in seen)) {
		seen[hex] = name
	}
}
/_HRESULT_TYPEDEF_\(0x[0-9A-Fa-f]+L\)/ {
	if (match($0, /0x[0-9A-Fa-f]+L/)) {
		add(toupper(substr($0, RSTART + 2, RLENGTH - 3)), $2)
	}
	next
}
# #define NAME (0xCODEU|(0xFACU<<16)|(3U<<30)) -- the *_e.h client headers.
/^#define [A-Za-z_0-9]+ \(0x[0-9A-Fa-f]+U\|\(0x[0-9A-Fa-f]+U<<16\)\|\(3U<<30\)\)/ {
	split($3, p, /[()|<]+/)
	code = toupper(substr(p[2], 3, length(p[2]) - 3))
	fac = toupper(substr(p[3], 3, length(p[3]) - 3))
	if (length(code) <= 4 && length(fac) <= 3) {
		add("C" pad(fac, 3) pad(code, 4), $2)
	}
}
END { for (h in seen) printf "\t0x%s: %c%s%c,\n", h, 34, seen[h], 34 }
' "$HEADER" $PKI_HEADERS | sort
echo "}"
